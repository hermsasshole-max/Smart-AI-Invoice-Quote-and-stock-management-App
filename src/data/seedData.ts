// Complete SQLite / Room DDL Schema for South African Field Service
export const SQLITE_DDL_SCHEMA = `
-- ========================================================================
-- SQLite / Android Room Database Schema for Solo Field Service Contractor
-- App: Harrys Aircon Electrical and Solar Services Pty.Ltd
-- ========================================================================

-- 1. INVENTORY & PRICE BOOK TABLE
CREATE TABLE IF NOT EXISTS inventory_items (
    id TEXT PRIMARY KEY NOT NULL,
    sku TEXT NOT NULL UNIQUE,
    barcode TEXT,
    description TEXT NOT NULL,
    category TEXT NOT NULL CHECK(category IN ('Electrical', 'HVAC', 'Solar', 'Security', 'Consumables')),
    unit TEXT NOT NULL CHECK(unit IN ('ea', 'm', 'roll', 'kg', 'box', 'set', 'pair', 'canister')),
    cost_price REAL NOT NULL,
    markup_pct REAL NOT NULL DEFAULT 30.0,
    selling_price REAL NOT NULL,
    stock_on_hand REAL NOT NULL DEFAULT 0.0,
    min_stock_alert REAL NOT NULL DEFAULT 1.0,
    canister_weight_kg REAL DEFAULT NULL,
    supplier_ref TEXT,
    notes TEXT,
    last_updated TEXT NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_inventory_sku ON inventory_items(sku);
CREATE INDEX IF NOT EXISTS idx_inventory_category ON inventory_items(category);

-- 2. CLIENTS DIRECTORY TABLE
CREATE TABLE IF NOT EXISTS clients (
    id TEXT PRIMARY KEY NOT NULL,
    name TEXT NOT NULL,
    company TEXT,
    phone TEXT NOT NULL,
    email TEXT,
    site_address TEXT NOT NULL,
    service_type TEXT NOT NULL,
    notes TEXT,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_clients_phone ON clients(phone);

-- 3. QUOTATIONS TABLE
CREATE TABLE IF NOT EXISTS quotations (
    id TEXT PRIMARY KEY NOT NULL,
    quote_number TEXT NOT NULL UNIQUE,
    client_id TEXT NOT NULL,
    client_name TEXT NOT NULL,
    client_phone TEXT NOT NULL,
    client_email TEXT,
    client_address TEXT NOT NULL,
    service_type TEXT NOT NULL,
    date TEXT NOT NULL,
    expiry_date TEXT NOT NULL,
    callout_fee REAL NOT NULL DEFAULT 750.0,
    master_labour_hours REAL NOT NULL DEFAULT 0.0,
    master_labour_rate REAL NOT NULL DEFAULT 550.0,
    assistant_labour_hours REAL NOT NULL DEFAULT 0.0,
    assistant_labour_rate REAL NOT NULL DEFAULT 150.0,
    travel_km REAL NOT NULL DEFAULT 0.0,
    travel_rate REAL NOT NULL DEFAULT 9.5,
    is_after_hours INTEGER NOT NULL DEFAULT 0,
    after_hours_multiplier REAL NOT NULL DEFAULT 1.0,
    materials_total REAL NOT NULL DEFAULT 0.0,
    labour_total REAL NOT NULL DEFAULT 0.0,
    travel_total REAL NOT NULL DEFAULT 0.0,
    subtotal REAL NOT NULL,
    vat_enabled INTEGER NOT NULL DEFAULT 1,
    vat_rate REAL NOT NULL DEFAULT 15.0,
    vat_amount REAL NOT NULL,
    total_amount REAL NOT NULL,
    status TEXT NOT NULL CHECK(status IN ('draft', 'sent', 'accepted', 'declined', 'converted')),
    notes TEXT,
    terms TEXT,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY(client_id) REFERENCES clients(id) ON DELETE RESTRICT
);

-- 4. QUOTE LINE ITEMS TABLE
CREATE TABLE IF NOT EXISTS quote_line_items (
    id TEXT PRIMARY KEY NOT NULL,
    quote_id TEXT NOT NULL,
    inventory_id TEXT,
    item_type TEXT NOT NULL CHECK(item_type IN ('material', 'labour', 'callout', 'travel', 'custom')),
    description TEXT NOT NULL,
    quantity REAL NOT NULL,
    unit TEXT NOT NULL,
    unit_cost REAL NOT NULL,
    unit_price REAL NOT NULL,
    total_price REAL NOT NULL,
    category TEXT,
    FOREIGN KEY(quote_id) REFERENCES quotations(id) ON DELETE CASCADE,
    FOREIGN KEY(inventory_id) REFERENCES inventory_items(id) ON DELETE SET NULL
);

-- 5. ACTIVE JOBS TABLE
CREATE TABLE IF NOT EXISTS jobs (
    id TEXT PRIMARY KEY NOT NULL,
    job_number TEXT NOT NULL UNIQUE,
    quote_id TEXT,
    client_id TEXT NOT NULL,
    client_name TEXT NOT NULL,
    client_phone TEXT NOT NULL,
    client_address TEXT NOT NULL,
    title TEXT NOT NULL,
    service_type TEXT NOT NULL,
    status TEXT NOT NULL CHECK(status IN ('pending', 'in_progress', 'completed', 'cancelled')),
    scheduled_date TEXT NOT NULL,
    completed_date TEXT,
    notes TEXT,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY(quote_id) REFERENCES quotations(id) ON DELETE SET NULL,
    FOREIGN KEY(client_id) REFERENCES clients(id) ON DELETE RESTRICT
);

-- 6. TAX INVOICES TABLE
CREATE TABLE IF NOT EXISTS invoices (
    id TEXT PRIMARY KEY NOT NULL,
    invoice_number TEXT NOT NULL UNIQUE,
    quote_id TEXT,
    job_id TEXT,
    client_id TEXT NOT NULL,
    client_name TEXT NOT NULL,
    client_phone TEXT NOT NULL,
    client_email TEXT,
    client_address TEXT NOT NULL,
    service_type TEXT NOT NULL,
    date TEXT NOT NULL,
    due_date TEXT NOT NULL,
    callout_fee REAL NOT NULL DEFAULT 0.0,
    labour_total REAL NOT NULL DEFAULT 0.0,
    travel_total REAL NOT NULL DEFAULT 0.0,
    materials_total REAL NOT NULL DEFAULT 0.0,
    subtotal REAL NOT NULL,
    vat_enabled INTEGER NOT NULL DEFAULT 1,
    vat_rate REAL NOT NULL DEFAULT 15.0,
    vat_amount REAL NOT NULL,
    total_amount REAL NOT NULL,
    amount_paid REAL NOT NULL DEFAULT 0.0,
    status TEXT NOT NULL CHECK(status IN ('draft', 'issued', 'paid', 'overdue')),
    payment_method TEXT,
    paid_date TEXT,
    notes TEXT,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY(quote_id) REFERENCES quotations(id) ON DELETE SET NULL,
    FOREIGN KEY(job_id) REFERENCES jobs(id) ON DELETE SET NULL,
    FOREIGN KEY(client_id) REFERENCES clients(id) ON DELETE RESTRICT
);

-- 7. SCANNED SUPPLIER INVOICE OCR LOGS
CREATE TABLE IF NOT EXISTS supplier_scans (
    id TEXT PRIMARY KEY NOT NULL,
    supplier_name TEXT NOT NULL,
    invoice_number TEXT,
    invoice_date TEXT,
    vat_number TEXT,
    subtotal REAL,
    vat_total REAL,
    grand_total REAL,
    items_count INTEGER NOT NULL,
    scanned_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
`;
